{
  const detailFile = 'src/pages/performance/components/PerformanceReviewDetail.vue'
  const detailPath = resolve(root, detailFile)
  if (existsSync(detailPath)) {
    const content = readFileSync(detailPath, 'utf8')
    const managerReviewActions = content.match(/if \(status === 'manager_review'\) \{[\s\S]*?\n {2}\}/)?.[0] || ''
    if (managerReviewActions.includes('action: \'withdraw\'')) {
      missingContent.push(`${detailFile}: manager_review action list must not include withdraw`)
    }
    if (!managerReviewActions.includes('action: \'return-employee\'') || !managerReviewActions.includes('action: \'submit-manager\'')) {
      missingContent.push(`${detailFile}: manager_review action list must include return-employee and submit-manager`)
    }
    const managerScopeActions = content.match(/manager: new Set\(\[[^\]]*\]\)/)?.[0] || ''
    if (managerScopeActions.includes('\'withdraw\'')) {
      missingContent.push(`${detailFile}: manager action scope must not include withdraw`)
    }
    const formControls = content.matchAll(/<u-(input|textarea)\b[\s\S]*?\/>/g)
    for (const match of formControls) {
      const tag = match[0]
      const customClass = tag.match(/custom-class="([^"]+)"/)?.[1] || ''
      const isPerformanceFormControl = customClass.split(/\s+/).some(className =>
        ['field-input', 'field-textarea'].includes(className),
      )
      if (isPerformanceFormControl && !tag.includes(':clearable="false"')) {
        missingContent.push(`${detailFile}: form ${match[1]} ${customClass || 'without custom-class'} must disable clearable`)
      }
    }
  }
}

