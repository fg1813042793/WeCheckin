for (const item of requiredContent) {
  const filePath = resolve(root, item.file)
  if (!existsSync(filePath)) {
    missingContent.push(`${item.file}: file is missing`)
    continue
  }
  const content = readFileSync(filePath, 'utf8')
  for (const pattern of item.patterns) {
    if (!content.includes(pattern)) {
      missingContent.push(`${item.file}: missing ${pattern}`)
    }
  }
}

for (const item of forbiddenContent) {
  const filePath = resolve(root, item.file)
  if (!existsSync(filePath)) {
    continue
  }
  const content = readFileSync(filePath, 'utf8')
  for (const pattern of item.patterns) {
    if (content.includes(pattern)) {
      missingContent.push(`${item.file}: forbidden ${pattern}`)
    }
  }
}

